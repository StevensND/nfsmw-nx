#!/usr/bin/env python3
"""The two variants of the glow's bright pass (nfsmw_resplandor_cielo) for the deko3d build.

The Vulkan build has them as SPIR-V made from a modified copy of the game's bright pass (container p_000094,
kHuellaBrightPass); that copy is game-derived, so it is not in the repository, and neither is what this makes. This
script makes the deko3d ones from the deko3d library's own rewritten HLSL of p_000094 (the one
shaders/nfsmw_regenerar_biblioteca_pcf.sh compiles with DEKO3D=1), with the same DXC options, and writes
app/src/nfsmw_dk_resplandor_spirv.h (gitignored). Without that header the deko3d build keeps the game's shader.

The game's bright pass scales the scene by middle gray over the adapted luminance and subtracts the threshold from
each channel. On saturated colors that leaves a blue halo around trees and roofs against the sky. The variants
take the same scaled color c and:
  natural  keep its hue: c * max(lum(c) - threshold, 0) / lum(c), lum with the Rec. 709 weights;
  suave    c * (sum of max(c - threshold, 0)) / sum(c): the per-channel energy, with c's hue.
These are the formulas of the Vulkan build's variants (read from its SPIR-V).

  tools/switch/dk_resplandor.py out/dk/hlsl_rw/p_000094.hlsl --dxc path/to/dxc [--salida app/src/...h]

DXC: the one the libraries are made with (v1.8.2502, linux_dxc_2025_02_20); with it the plain shader comes out
byte-identical to the library's, which this checks when --referencia is given.
"""

import argparse
import os
import struct
import subprocess
import sys
import tempfile

ORIGINAL = """\tr1.yzw = r0.yxz * g_fMiddleGray.xxx;
\tps = clamp(rcp(r1.x), FLT_MIN, FLT_MAX);
\tr1.x = ps;
\tr1.xyz = r1.zyw * r1.xxx + -g_fBrightPassThreshold.xxx;
\toC0.xyz = max(r1.xyz, c255.yyy);
"""

ESCALA = "\tr1.yzw = r0.xyz * g_fMiddleGray.xxx * clamp(rcp(r1.x), FLT_MIN, FLT_MAX);\n"

VARIANTES = {
    "Natural": ESCALA
    + "\tr2.x = dot(r1.yzw, float3(0.2125, 0.7154, 0.0721));\n"
    + "\tr2.y = max(r2.x - g_fBrightPassThreshold.x, 0.0) / max(r2.x, 0.0001);\n"
    + "\toC0.xyz = r1.yzw * r2.yyy;\n",
    "Suave": ESCALA
    + "\tr2.xyz = max(r1.yzw - g_fBrightPassThreshold.xxx, 0.0);\n"
    + "\toC0.xyz = r1.yzw * ((r2.x + r2.y + r2.z) / max(r1.y + r1.z + r1.w, 0.0001));\n",
}

OPCIONES = ["-spirv", "-T", "ps_6_6", "-E", "main", "-HV", "2021", "-fspv-target-env=vulkan1.2",
            "-fvk-use-dx-layout", "-Werror=parameter-usage", "-DNFSMW_DEKO3D"]


def compilar(dxc, hlsl, salida):
    r = subprocess.run([dxc, *OPCIONES, "-Fo", salida, hlsl], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"DXC rechazo {hlsl}:\n{r.stderr}")
    return open(salida, "rb").read()


def main():
    a = argparse.ArgumentParser()
    a.add_argument("hlsl", help="p_000094.hlsl reescrito de la biblioteca de deko3d")
    a.add_argument("--dxc", default="dxc")
    a.add_argument("--referencia", help="spirv_dk/p_000094.spv de la biblioteca, para comprobar el DXC")
    a.add_argument("--salida", default=os.path.join(os.path.dirname(__file__), "..", "..", "app", "src",
                                                   "nfsmw_dk_resplandor_spirv.h"))
    args = a.parse_args()
    fuente = open(args.hlsl, encoding="utf-8").read()
    if fuente.count(ORIGINAL) != 1:
        sys.exit("el HLSL no tiene el bright pass esperado (p_000094 de la biblioteca de deko3d?)")
    lineas = ["// Generated by tools/switch/dk_resplandor.py from the game's bright pass: do not commit.",
              "#pragma once", "#include <cstdint>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        if args.referencia:
            propio = compilar(args.dxc, args.hlsl, os.path.join(tmp, "original.spv"))
            if propio != open(args.referencia, "rb").read():
                sys.exit("este DXC no da el mismo SPIR-V que la biblioteca: usa el de la biblioteca (v1.8.2502)")
        for nombre, cuerpo in VARIANTES.items():
            hlsl = os.path.join(tmp, f"{nombre}.hlsl")
            open(hlsl, "w", encoding="utf-8").write(fuente.replace(ORIGINAL, cuerpo))
            spirv = compilar(args.dxc, hlsl, os.path.join(tmp, f"{nombre}.spv"))
            palabras = struct.unpack(f"<{len(spirv) // 4}I", spirv)
            lineas.append(f"inline constexpr uint32_t kSpirvDkResplandor{nombre}[] = {{")
            for i in range(0, len(palabras), 8):
                lineas.append("    " + ", ".join(f"0x{p:08X}u" for p in palabras[i:i + 8]) + ",")
            lineas.append("};")
            print(f"{nombre}: {len(spirv)} bytes de SPIR-V")
    open(args.salida, "w", encoding="utf-8").write("\n".join(lineas) + "\n")
    print(f"escrito {os.path.normpath(args.salida)}")


if __name__ == "__main__":
    main()
